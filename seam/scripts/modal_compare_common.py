"""Shared attack split and SEAM-style evaluation for defense comparisons.

The public RepNoise refusals are not verified to have been generated by GPT-4o.
This is a comparison protocol, not a reproduction of every paper's own metric.
"""

import hashlib
import json
import os
import random
import subprocess
import sys
from pathlib import Path

import requests

PUBLIC_DATA_URL = (
    "https://raw.githubusercontent.com/domenicrosati/representation-noising/"
    "main/data/beavertails_with_refusals_train.json"
)
MODEL = "meta-llama/Llama-2-7b-chat-hf"
ATTACK_LRS = ("2e-5", "5e-5", "8e-5", "1e-4", "2e-4")
TASKS = ("arc_easy", "mmlu", "truthfulqa_mc2", "hellaswag")


def write_json(path: Path, payload):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2, default=str), encoding="utf-8")


def prepare_split(seed: int, data_dir: Path):
    """Match SEAM's 4k/1k split; reserve a further 1k for CTRAP's 5k."""
    response = requests.get(PUBLIC_DATA_URL, timeout=120)
    response.raise_for_status()
    source_sha256 = hashlib.sha256(response.content).hexdigest()
    rows = [
        row for row in response.json()
        if row.get("is_safe") is False and row.get("prompt")
        and row.get("response") and row.get("refusal")
    ]
    random.Random(seed).shuffle(rows)
    if len(rows) < 6000:
        raise ValueError(f"Need at least 6,000 eligible RepNoise rows, got {len(rows)}")
    data_dir.mkdir(parents=True, exist_ok=False)
    attack = rows[4000:5000]
    defense = rows[:4000] + rows[5000:6000]
    write_json(data_dir / "attack.json", attack)
    write_json(data_dir / "ctrap_defense.json", defense)
    return {
        "source": PUBLIC_DATA_URL,
        "source_sha256": source_sha256,
        "refusal_provenance": "RepNoise public data; GPT-4o not verified",
        "eligible_rows": len(rows),
        "seam_defense_indices": "0:4000",
        "shared_attack_indices": "4000:5000",
        "ctrap_extra_defense_indices": "5000:6000",
        "attack_count": len(attack),
        "ctrap_defense_count": len(defense),
    }


def evaluate_sweep(method: str, seed: int, test_size: int, output: Path,
                   attack_path: Path, defended_model: str, stage,
                   lora_attack_config: str = "", direct_gpu_load: bool = False):
    """Run identical SEAM evaluator on base and defended model, before/after attack."""
    env = os.environ.copy()
    env.update({
        "WANDB_MODE": "disabled", "TOKENIZERS_PARALLELISM": "false",
        "PYTHONUNBUFFERED": "1", "CUDA_VISIBLE_DEVICES": "0",
    })
    if direct_gpu_load:
        env["SEAM_DIRECT_GPU_LOAD"] = "1"
    summary = {"method": method, "seed": seed, "metrics": {}}
    for label, model_path in (("base", MODEL), (method.lower(), defended_model)):
        for lr in (None, *ATTACK_LRS):
            key = f"{label}-pre" if lr is None else f"{label}-attack-lr{lr}"
            stage(key)
            metric_path = output / "metrics" / f"{key}.json"
            args = [
                sys.executable, "-m", "src.eval",
                "--model_name", model_path, "--tokenizer_name", MODEL,
                "--data_path", str(attack_path),
                "--output_dir", str(output / "attack_work" / key),
                "--seed", str(seed), "--report_to", "none",
                "--pre_utility", "false", "--post_utility", "true",
                "--gpt_eval", "false", "--test_size", str(test_size),
                "--attack", "false" if lr is None else "true",
                "--attack_dataset", "true", "--attack_size", "1000",
                "--per_device_train_batch_size", "4", "--utility_batch_size", "8",
                "--gradient_checkpointing", "true",
                "--max_steps", "250", "--save_strategy", "no",
                "--result_path", str(metric_path), "--utility_tasks", *TASKS,
                "--wandb_run_name", key,
            ]
            if lr is not None:
                args.extend(("--learning_rate", lr))
                if lora_attack_config:
                    args.extend(("--lora_attack", "true",
                                 "--lora_attack_config", lora_attack_config))
            print("COMPARE_COMMAND", " ".join(args), flush=True)
            subprocess.run(args, cwd="/root/seam", env=env, check=True)
            summary["metrics"][key] = json.loads(metric_path.read_text(encoding="utf-8"))
            stage(key + "-saved")
    write_json(output / "summary.json", summary)
    return summary
